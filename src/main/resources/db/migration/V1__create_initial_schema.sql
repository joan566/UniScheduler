CREATE TYPE user_status AS ENUM ('ACTIVE', 'INACTIVE', 'SUSPENDED');
CREATE TYPE period_status AS ENUM ('PLANNED', 'ACTIVE', 'CLOSED');
CREATE TYPE enrollment_detail_status AS ENUM ('ENROLLED', 'COMPLETED', 'WITHDRAWN', 'FAILED');

CREATE TABLE roles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL
);

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name varchar(100) NOT NULL,
    last_name varchar(100) NOT NULL,
    document_type varchar(30) NOT NULL,
    document_number varchar(30) NOT NULL UNIQUE,
    birth_date date,
    gender varchar(20),
    phone_number varchar(20),
    address varchar(255),
    email varchar(150) NOT NULL UNIQUE,
    password varchar(255) NOT NULL,
    status user_status NOT NULL,
    created_at timestamp DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE user_roles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users (id),
    role_id bigint NOT NULL REFERENCES roles (id),
    CONSTRAINT uq_user_roles_user_id_role_id UNIQUE (user_id, role_id)
);

CREATE TABLE academic_programs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(150) NOT NULL,
    total_semesters integer NOT NULL
);

CREATE TABLE courses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(150) NOT NULL,
    code varchar(30) NOT NULL UNIQUE,
    credits integer NOT NULL,
    description text
);

CREATE TABLE teachers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(150) NOT NULL
);

CREATE TABLE academic_periods (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(30) NOT NULL UNIQUE,
    name varchar(100) NOT NULL,
    start_date date NOT NULL,
    end_date date NOT NULL,
    status period_status NOT NULL
);

CREATE TABLE semester_templates (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id bigint NOT NULL REFERENCES academic_programs (id),
    semester integer NOT NULL
);

CREATE TABLE semester_template_details (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id bigint NOT NULL REFERENCES semester_templates (id),
    course_id bigint NOT NULL REFERENCES courses (id)
);

CREATE TABLE prerequisites (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id bigint NOT NULL REFERENCES courses (id),
    prerequisite_course_id bigint NOT NULL REFERENCES courses (id),
    CONSTRAINT uq_prerequisites_course_pair UNIQUE (course_id, prerequisite_course_id)
);

CREATE TABLE "groups" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id bigint NOT NULL REFERENCES courses (id),
    teacher_id bigint NOT NULL REFERENCES teachers (id),
    group_code varchar(30) NOT NULL,
    capacity integer NOT NULL,
    academic_period_id bigint NOT NULL REFERENCES academic_periods (id),
    created_at timestamp DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp,
    CONSTRAINT uq_groups_course_period_code UNIQUE (course_id, academic_period_id, group_code)
);

CREATE TABLE group_schedules (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id bigint NOT NULL REFERENCES "groups" (id),
    day_of_week varchar(20) NOT NULL,
    start_time time NOT NULL,
    end_time time NOT NULL,
    classroom varchar(50)
);

CREATE TABLE students (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_code varchar(30) NOT NULL UNIQUE,
    user_id bigint NOT NULL UNIQUE REFERENCES users (id),
    academic_program_id bigint NOT NULL REFERENCES academic_programs (id)
);

CREATE TABLE enrollments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL REFERENCES students (id),
    academic_program_id bigint NOT NULL REFERENCES academic_programs (id),
    enrollment_date date NOT NULL,
    academic_period_id bigint NOT NULL REFERENCES academic_periods (id),
    created_at timestamp DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_enrollments_student_period UNIQUE (student_id, academic_period_id)
);

CREATE TABLE enrollment_details (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_id bigint NOT NULL REFERENCES enrollments (id),
    group_id bigint NOT NULL REFERENCES "groups" (id),
    status enrollment_detail_status NOT NULL,
    final_grade decimal(4, 2),
    created_at timestamp DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp,
    CONSTRAINT uq_enrollment_details_enrollment_group UNIQUE (enrollment_id, group_id)
);
